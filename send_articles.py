def send_doc(filename, content):
    body = b""
    for name, val in (("chat_id", CHAT),
                      ("caption", f"📝 Статья: {filename} — перешли этот файл боту, чтобы опубликовать.")):
        body += (f"--{BOUNDARY}\r\nContent-Disposition: form-data; name=\"{name}\"\r\n\r\n{val}\r\n").encode()
